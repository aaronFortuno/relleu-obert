const accents={À:['A','grave'],Á:['A','acute'],È:['E','grave'],É:['E','acute'],Í:['I','acute'],Ï:['I','dots'],Ò:['O','grave'],Ó:['O','acute'],Ú:['U','acute'],Ü:['U','dots'],Ç:['C','cedilla']};
export function printableText(text){
  if(typeof text!=='string')throw Error('El text de la placa no és vàlid.');
  const normalized=text.normalize('NFC').replaceAll('’',"'").replaceAll('“','"').replaceAll('”','"');
  if([...normalized].length>60)throw Error('Cada línia admet fins a 60 caràcters.');
  return [...normalized].map(c=>{const upper=c.toUpperCase();if(upper.length!==1||!(upper===' '||rows[upper]||accents[upper]))throw Error(`Caràcter «${c}» no admès a la placa.`);return upper;}).join('');
}
export function glyphRectangles(char){
  if(char===' ')return [];
  const [base,accent]=accents[char]||[char,null],pattern=rows[base];
  if(!pattern)throw Error('Glif no admès.');
  const rects=[];
  pattern.split('/').forEach((row,y)=>{for(let x=0;x<5;){if(row[x]!=='1'){x++;continue;}const start=x;while(x<5&&row[x]==='1')x++;rects.push([start,6-y,x-start,1]);}});
  if(accent==='acute')rects.push([2,7.5,1,1],[3,8.5,1,1]);
  if(accent==='grave')rects.push([2,7.5,1,1],[1,8.5,1,1]);
  if(accent==='dots')rects.push([1,8,1,1],[3,8,1,1]);
  if(accent==='cedilla')rects.push([2,-1,1,1],[1,-2,1,1]);
  return rects;
}
